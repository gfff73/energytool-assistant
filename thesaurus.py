def expansions(text, strong_only=False):
    """Return knowledge-base words implied by the client's wording."""
    lowered = text.casefold().replace("ё", "е")
    return " ".join(words for pattern, words, strong in COMPILED
                    if (strong or not strong_only) and pattern.search(lowered))
